//! Collects the typed metadata properties from `src/properties/*.rs`.
//!
//! Each file is one property key: `<snake_case key>.rs` declares
//! `pub(super) const SPEC: MetadataPropertySpec` (or `SPEC_1`, `SPEC_2`, … for
//! a key with several owner-specific specifications). This script writes the
//! module declarations, the `MetaPropertyKey` enum and `METADATA_PROPERTY_SPECS`
//! sorted by public name, so a new property adds a file and does not edit a
//! shared list. A `// serde-rename: <Name>` line sets the key's serialized name.
//! `scripts/ci/size-filters.py` and `scripts/ci/removed_tests.py` resolve the
//! same directory.
use std::path::{Path, PathBuf};

const PROPERTIES: &str = "src/properties";
const GENERATED: &str = "properties_modules.rs";

struct Property {
    module: String,
    variant: String,
    serde_rename: Option<String>,
    specs: Vec<(String, String)>,
}

fn main() {
    let manifest = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("Cargo sets CARGO_MANIFEST_DIR"),
    );
    let directory = manifest.join(PROPERTIES);
    println!("cargo:rerun-if-changed={PROPERTIES}");
    let mut files = std::fs::read_dir(&directory)
        .unwrap_or_else(|error| panic!("read {}: {error}", directory.display()))
        .map(|entry| entry.expect("property entry is readable").path())
        .filter(|path| path.is_file() && path.extension().is_some_and(|ext| ext == "rs"))
        .collect::<Vec<_>>();
    files.sort();
    let properties = files.iter().map(|path| property(path)).collect::<Vec<_>>();

    let mut generated =
        String::from("// @generated by crates/unica-metadata/build.rs; do not edit.\n");
    for property in &properties {
        let path = directory.join(format!("{}.rs", property.module));
        let path = path
            .to_str()
            .expect("property path is UTF-8")
            .replace('\\', "/");
        generated.push_str(&format!(
            "#[path = {path:?}]\nmod {};\n",
            ident(&property.module)
        ));
    }
    generated.push_str(
        "\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize)]\n\
         #[serde(rename_all = \"PascalCase\")]\npub enum MetaPropertyKey {\n",
    );
    for property in &properties {
        if let Some(name) = &property.serde_rename {
            generated.push_str(&format!("    #[serde(rename = {name:?})]\n"));
        }
        generated.push_str(&format!("    {},\n", property.variant));
    }
    generated.push_str("}\n\npub const METADATA_PROPERTY_SPECS: &[MetadataPropertySpec] = &[\n");
    let mut specs = properties
        .iter()
        .flat_map(|property| {
            property.specs.iter().map(move |(constant, public)| {
                (public.clone(), property.module.clone(), constant.clone())
            })
        })
        .collect::<Vec<_>>();
    // A stable sort keeps a key's owner-specific specifications in file order.
    specs.sort_by(|left, right| left.0.cmp(&right.0));
    for (_, module, constant) in specs {
        generated.push_str(&format!("    {}::{constant},\n", ident(&module)));
    }
    generated.push_str("];\n");

    let output =
        PathBuf::from(std::env::var_os("OUT_DIR").expect("Cargo sets OUT_DIR")).join(GENERATED);
    // Rewriting identical bytes would invalidate the crate's incremental state.
    if std::fs::read_to_string(&output).ok().as_deref() != Some(generated.as_str()) {
        std::fs::write(&output, generated)
            .unwrap_or_else(|error| panic!("write {}: {error}", output.display()));
    }
}

/// A module name as a Rust path segment: keys such as `Type` and `Use` give
/// keyword file names, which become raw identifiers.
fn ident(module: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "do",
        "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in",
        "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
        "return", "static", "struct", "trait", "true", "try", "type", "typeof", "unsafe",
        "unsized", "use", "virtual", "where", "while", "yield",
    ];
    assert!(
        !matches!(module, "self" | "super" | "crate"),
        "property file {module}.rs cannot be a path keyword"
    );
    if KEYWORDS.contains(&module) {
        format!("r#{module}")
    } else {
        module.to_string()
    }
}

fn property(path: &Path) -> Property {
    let module = path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .unwrap_or_else(|| panic!("property file name is not UTF-8: {}", path.display()))
        .to_string();
    let valid = module
        .chars()
        .next()
        .is_some_and(|first| first.is_ascii_lowercase())
        && module
            .chars()
            .all(|ch| ch == '_' || ch.is_ascii_lowercase() || ch.is_ascii_digit())
        && !module.contains("__")
        && !module.ends_with('_');
    assert!(
        valid,
        "property file {} must be the snake_case form of its key",
        path.display()
    );
    let variant = module
        .split('_')
        .map(|word| {
            let mut chars = word.chars();
            chars
                .next()
                .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect::<String>();
    let text = std::fs::read_to_string(path)
        .unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
    let serde_rename = text
        .lines()
        .find_map(|line| line.trim().strip_prefix("// serde-rename: "))
        .map(|name| name.trim().to_string());
    let mut specs = Vec::new();
    let mut rest = text.as_str();
    while let Some(at) = rest.find("pub(super) const SPEC") {
        let declaration = &rest[at + "pub(super) const ".len()..];
        let constant = declaration
            .split(':')
            .next()
            .expect("SPEC declaration has a type")
            .trim()
            .to_string();
        // The first string literal of the specification is its public name.
        let public = declaration
            .split('"')
            .nth(1)
            .unwrap_or_else(|| panic!("{}: {constant} has no public name", path.display()))
            .to_string();
        specs.push((constant, public));
        rest = &declaration[1..];
    }
    assert!(
        !specs.is_empty(),
        "property file {} declares no `pub(super) const SPEC`",
        path.display()
    );
    assert!(
        text.contains(&format!("MetaPropertyKey::{variant}")),
        "property file {} must declare a specification of MetaPropertyKey::{variant}",
        path.display()
    );
    Property {
        module,
        variant,
        serde_rename,
        specs,
    }
}
