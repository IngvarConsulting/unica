//! Collects the node kinds from `src/kinds/*.rs`.
//!
//! Each file declares one kind: `<snake_case variant>.rs` holds
//! `pub(super) const KIND: KindDeclaration`. This script writes the module
//! declarations, the `NodeKind` enum with the files' leading `//!` lines as
//! variant docs, `NodeKind::declaration` and the `DECLARED` table in file-name
//! order. A new kind adds a file and does not edit a shared list; two changes
//! with different kinds do not conflict.
//!
//! The module declarations reach `kinds.rs` through a macro: `mod` in a macro
//! expanded there resolves as if it were written there, so `kinds/<stem>.rs`
//! is found. `scripts/ci/check-discovered-modules-format.py` formats the files.
use std::path::{Path, PathBuf};

const KINDS: &str = "src/kinds";
const GENERATED: &str = "kinds.rs";
/// Lowercase Rust keywords, strict and reserved: such a module is written as a
/// raw identifier.
const KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "crate",
    "do", "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl",
    "in", "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
    "return", "static", "struct", "trait", "true", "try", "type", "typeof", "unsafe", "unsized",
    "use", "virtual", "where", "while", "yield",
];

struct Kind {
    module: String,
    variant: String,
    docs: Vec<String>,
}

fn main() {
    let manifest = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("Cargo sets CARGO_MANIFEST_DIR"),
    );
    let directory = manifest.join(KINDS);
    // A directory makes Cargo rerun the script when any file inside it is
    // added, removed or changed.
    println!("cargo:rerun-if-changed={KINDS}");
    let mut files = std::fs::read_dir(&directory)
        .unwrap_or_else(|error| panic!("read {}: {error}", directory.display()))
        .map(|entry| entry.expect("kind entry is readable").path())
        .filter(|path| path.is_file() && path.extension().is_some_and(|ext| ext == "rs"))
        .collect::<Vec<_>>();
    files.sort();
    let kinds = files.iter().map(|path| kind(path)).collect::<Vec<_>>();
    assert!(
        !kinds.is_empty(),
        "{} declares no kinds",
        directory.display()
    );

    let mut generated = String::from(
        "// @generated by crates/unica-address/build.rs; do not edit.\n\
         macro_rules! declare_kind_modules {\n    () => {\n",
    );
    for kind in &kinds {
        generated.push_str(&format!("        mod {};\n", kind.module));
    }
    generated.push_str(
        "    };\n}\n\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\npub enum NodeKind {\n",
    );
    for kind in &kinds {
        for line in &kind.docs {
            generated.push_str(&format!("    #[doc = {line:?}]\n"));
        }
        generated.push_str(&format!("    {},\n", kind.variant));
    }
    generated.push_str(
        "}\n\nimpl NodeKind {\n    /// The declaration of this kind.\n    \
         pub const fn declaration(self) -> &'static KindDeclaration {\n        match self {\n",
    );
    for kind in &kinds {
        generated.push_str(&format!(
            "            Self::{} => &{}::KIND,\n",
            kind.variant, kind.module
        ));
    }
    generated.push_str("        }\n    }\n}\n\n");
    generated.push_str(&format!(
        "/// Every declaration in file-name order.\npub(crate) const DECLARED: [(NodeKind, KindDeclaration); {}] = [\n",
        kinds.len()
    ));
    for kind in &kinds {
        generated.push_str(&format!(
            "    (NodeKind::{}, {}::KIND),\n",
            kind.variant, kind.module
        ));
    }
    generated.push_str("];\n");

    let output =
        PathBuf::from(std::env::var_os("OUT_DIR").expect("Cargo sets OUT_DIR")).join(GENERATED);
    // Rewriting identical bytes would invalidate the crate's incremental state.
    if std::fs::read_to_string(&output).ok().as_deref() != Some(generated.as_str()) {
        std::fs::write(&output, generated)
            .unwrap_or_else(|error| panic!("write {}: {error}", output.display()));
    }
}

fn kind(path: &Path) -> Kind {
    let stem = path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .unwrap_or_else(|| panic!("kind file name is not UTF-8: {}", path.display()));
    let valid = stem.split('_').all(|word| {
        let mut chars = word.chars();
        chars.next().is_some_and(|first| first.is_ascii_lowercase())
            && chars.all(|ch| ch.is_ascii_lowercase() || ch.is_ascii_digit())
    });
    assert!(
        valid,
        "kind file {} must be a snake_case variant name",
        path.display()
    );
    let variant = stem
        .split('_')
        .map(|word| {
            let mut chars = word.chars();
            let first = chars.next().expect("a word is not empty");
            first.to_ascii_uppercase().to_string() + chars.as_str()
        })
        .collect::<String>();
    let module = if KEYWORDS.contains(&stem) {
        format!("r#{stem}")
    } else {
        stem.to_string()
    };
    let source = std::fs::read_to_string(path)
        .unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
    let docs = source
        .lines()
        .map_while(|line| line.strip_prefix("//!"))
        .map(|line| line.strip_prefix(' ').unwrap_or(line).to_string())
        .collect::<Vec<_>>();
    Kind {
        module,
        variant,
        docs,
    }
}
