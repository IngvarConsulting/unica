//! Discovers the modules of the crate from `src/*.rs`.
//!
//! Every file except `lib.rs` becomes `pub mod <file stem>;`, in file-name order.
//! A file whose leading comments hold the line `// module: private` becomes
//! `mod <file stem>;`. A new module therefore does not edit a shared list, and
//! two changes that add different modules do not conflict.
//!
//! The declarations reach `lib.rs` through a macro: `mod` in a macro expanded
//! there resolves as if it were written there, so a module keeps its
//! `<stem>/<child>.rs` children. `#[path]` would make them siblings instead.
//! `scripts/ci/removed_tests.py` and `scripts/ci/check-discovered-modules-format.py`
//! resolve the same directory.
use std::path::{Path, PathBuf};

const MODULES: &str = "src";
const GENERATED: &str = "metadata_designer_modules.rs";
const PRIVATE_MARKER: &str = "// module: private";
/// Lowercase Rust keywords, strict and reserved, and `_`: `mod <keyword>;` does
/// not compile.
const KEYWORDS: &[&str] = &[
    "_", "abstract", "as", "async", "await", "become", "box", "break", "const", "continue",
    "crate", "do", "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if",
    "impl", "in", "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub",
    "ref", "return", "self", "static", "struct", "super", "trait", "true", "try", "type", "typeof",
    "unsafe", "unsized", "use", "virtual", "where", "while", "yield",
];

fn main() {
    let manifest = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("Cargo sets CARGO_MANIFEST_DIR"),
    );
    let directory = manifest.join(MODULES);
    // A directory makes Cargo rerun the script when any file inside it is
    // added, removed or changed.
    println!("cargo:rerun-if-changed={MODULES}");
    let mut files = std::fs::read_dir(&directory)
        .unwrap_or_else(|error| panic!("read {}: {error}", directory.display()))
        .map(|entry| entry.expect("module entry is readable").path())
        .filter(|path| {
            path.is_file()
                && path.extension().is_some_and(|ext| ext == "rs")
                && path.file_name().is_some_and(|name| name != "lib.rs")
        })
        .collect::<Vec<_>>();
    files.sort();
    let mut generated = String::from(
        "// @generated by crates/unica-metadata-designer/build.rs; do not edit.\n\
         macro_rules! declare_modules {\n    () => {\n",
    );
    for path in &files {
        let visibility = if is_private(path) { "" } else { "pub " };
        generated.push_str(&format!("        {visibility}mod {};\n", module_name(path)));
    }
    generated.push_str("    };\n}\n");
    let output =
        PathBuf::from(std::env::var_os("OUT_DIR").expect("Cargo sets OUT_DIR")).join(GENERATED);
    // Rewriting identical bytes would invalidate the crate's incremental state.
    if std::fs::read_to_string(&output).ok().as_deref() != Some(generated.as_str()) {
        std::fs::write(&output, generated)
            .unwrap_or_else(|error| panic!("write {}: {error}", output.display()));
    }
}

fn is_private(path: &Path) -> bool {
    let source = std::fs::read_to_string(path)
        .unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
    let header = source
        .lines()
        .take_while(|line| line.trim_start().starts_with("//"))
        .count();
    let mut marked = false;
    for (index, line) in source.lines().enumerate() {
        if line.contains("module: private") {
            // A misspelled or misplaced marker would silently publish the module.
            assert!(
                index < header && line.trim_end() == PRIVATE_MARKER,
                "{}:{}: write the marker as `{PRIVATE_MARKER}` in the leading comments",
                path.display(),
                index + 1,
            );
            marked = true;
        }
    }
    marked
}

fn module_name(path: &Path) -> &str {
    let name = path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .unwrap_or_else(|| panic!("module name is not UTF-8: {}", path.display()));
    let mut chars = name.chars();
    let valid = chars
        .next()
        .is_some_and(|first| first == '_' || first.is_ascii_lowercase())
        && chars.all(|ch| ch == '_' || ch.is_ascii_lowercase() || ch.is_ascii_digit());
    assert!(
        valid && !KEYWORDS.contains(&name),
        "module file {} must be a snake_case Rust identifier that is not a keyword",
        path.display()
    );
    name
}
