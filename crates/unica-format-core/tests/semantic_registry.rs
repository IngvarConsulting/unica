#[test]
fn registries_parse_only_core_owned_stable_strings() {
    assert_eq!(
        SemanticPropertyId::parse("metadata.name"),
        Some(SemanticPropertyId::METADATA_NAME)
    );
    assert_eq!(
        SemanticRelationId::parse("attributes"),
        Some(SemanticRelationId::ATTRIBUTES)
    );
    assert_eq!(
        SemanticObjectKind::parse("document"),
        Some(SemanticObjectKind::Document)
    );
    assert_eq!(
        SemanticEnumValue::parse("recorderPosition"),
        Some(SemanticEnumValue::RECORDER_POSITION)
    );

    assert!(SemanticPropertyId::parse("adapter.custom").is_none());
    assert!(SemanticRelationId::parse("nativeChildren").is_none());
    assert!(SemanticObjectKind::parse("metadataObject:Native").is_none());
    assert!(SemanticEnumValue::parse("adapterValue").is_none());
}
