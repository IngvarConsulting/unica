use std::collections::BTreeSet;

use unica_format_core::semantic_ids::{
    SemanticEnumValue, SemanticFacetId, SemanticObjectKind, SemanticPropertyId, SemanticRelationId,
};

fn assert_complete_unique<T: Copy>(
    actual: &[T],
    expected: &[&str],
    stable_string: impl Fn(T) -> &'static str,
) {
    let actual = actual
        .iter()
        .copied()
        .map(stable_string)
        .collect::<Vec<_>>();
    assert_eq!(actual, expected);
    assert_eq!(
        actual.iter().copied().collect::<BTreeSet<_>>().len(),
        actual.len(),
        "semantic registry contains duplicate stable strings"
    );
}

