//! Discovers the submodules of modules from their directories.
//!
//! Every `*.rs` file in a directory of `MODULES` becomes `mod <file stem>;` of
//! the module named after it, in file-name order. A new file therefore does not
//! edit a shared registration list, and two changes that add different files do
//! not conflict.
//! `scripts/ci/removed_tests.py` and `scripts/ci/check-discovered-modules-format.py`
//! resolve the same directories.
use std::path::{Path, PathBuf};

/// The directory of a module and the file its declarations are written to.
const MODULES: &[(&str, &str)] = &[
    (
        "src/infrastructure/native_operations/apply_families/metadata/tests",
        "apply_families_metadata_tests_modules.rs",
    ),
    (
        "src/infrastructure/v13_read/tests",
        "v13_read_tests_modules.rs",
    ),
    (
        "src/infrastructure/v13_read_port",
        "v13_read_port_modules.rs",
    ),
    (
        "src/infrastructure/format_families",
        "format_families_modules.rs",
    ),
];
/// Directories whose modules each declare one item; the generated file lists
/// them in file-name order as a slice constant: (directory, file, constant, item, type).
const REGISTRIES: &[(&str, &str, &str, &str, &str)] = &[(
    "src/infrastructure/format_families",
    "format_families_registry.rs",
    "DECLARED_FAMILIES",
    "FAMILY",
    "&[&dyn FormatFamily]",
)];
/// Lowercase Rust keywords, strict and reserved, and `_`: `mod <keyword>;` does
/// not compile. `gen` is reserved from edition 2024; rejecting it now keeps the
/// module names valid across an edition change.
const KEYWORDS: &[&str] = &[
    "_", "abstract", "as", "async", "await", "become", "box", "break", "const", "continue",
    "crate", "do", "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if",
    "impl", "in", "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub",
    "ref", "return", "self", "static", "struct", "super", "trait", "true", "try", "type", "typeof",
    "unsafe", "unsized", "use", "virtual", "where", "while", "yield",
];

fn main() {
    let manifest = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("Cargo sets CARGO_MANIFEST_DIR"),
    );
    for (directory, generated) in MODULES {
        write_declarations(&manifest, directory, generated);
    }
    for (directory, generated, constant, item, ty) in REGISTRIES {
        write_registry(&manifest, directory, generated, constant, item, ty);
    }
}

fn module_files(directory: &Path) -> Vec<PathBuf> {
    let mut files = std::fs::read_dir(directory)
        .unwrap_or_else(|error| panic!("read {}: {error}", directory.display()))
        .map(|entry| entry.expect("module entry is readable").path())
        .filter(|path| path.is_file() && path.extension().is_some_and(|ext| ext == "rs"))
        .collect::<Vec<_>>();
    files.sort();
    files
}

fn write_generated(name: &str, generated: String) {
    let output = PathBuf::from(std::env::var_os("OUT_DIR").expect("Cargo sets OUT_DIR")).join(name);
    // Rewriting identical bytes would invalidate the crate's incremental state.
    if std::fs::read_to_string(&output).ok().as_deref() != Some(generated.as_str()) {
        std::fs::write(&output, generated)
            .unwrap_or_else(|error| panic!("write {}: {error}", output.display()));
    }
}

fn write_registry(
    manifest: &Path,
    relative: &str,
    name: &str,
    constant: &str,
    item: &str,
    ty: &str,
) {
    println!("cargo:rerun-if-changed={relative}");
    let mut generated = format!(
        "// @generated by crates/unica-coder/build.rs; do not edit.\nconst {constant}: {ty} = &[\n"
    );
    for path in module_files(&manifest.join(relative)) {
        generated.push_str(&format!("    {}::{item},\n", module_name(&path)));
    }
    generated.push_str("];\n");
    write_generated(name, generated);
}

fn write_declarations(manifest: &Path, relative: &str, name: &str) {
    let directory = manifest.join(relative);
    // A directory makes Cargo rerun the script when any file inside it is
    // added, removed or changed.
    println!("cargo:rerun-if-changed={relative}");
    let files = module_files(&directory);
    let mut generated =
        String::from("// @generated by crates/unica-coder/build.rs; do not edit.\n");
    for path in files {
        let name = module_name(&path);
        let path = path
            .to_str()
            .unwrap_or_else(|| panic!("module path is not UTF-8: {}", path.display()));
        generated.push_str(&format!(
            "#[path = {:?}]\nmod {name};\n",
            path.replace('\\', "/")
        ));
    }
    write_generated(name, generated);
}

fn module_name(path: &Path) -> &str {
    let name = path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .unwrap_or_else(|| panic!("module name is not UTF-8: {}", path.display()));
    let mut chars = name.chars();
    let valid = chars
        .next()
        .is_some_and(|first| first == '_' || first.is_ascii_lowercase())
        && chars.all(|ch| ch == '_' || ch.is_ascii_lowercase() || ch.is_ascii_digit());
    assert!(
        valid && !KEYWORDS.contains(&name),
        "module file {} must be a snake_case Rust identifier that is not a keyword",
        path.display()
    );
    name
}
